//! Reference steering curves adapted to Model 1's native 20–80–E0 span.
//! Source: current SM2 input.cpp and Supermodel Libretro libretro.cpp.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Response {
    #[default]
    Linear,
    Progressive,
    Fbneo,
}
impl Response {
    pub fn parse(value: Option<&str>) -> Self {
        match value {
            Some("progressive") => Self::Progressive,
            Some("fbneo") => Self::Fbneo,
            _ => Self::Linear,
        }
    }
    pub fn apply(self, value: u8) -> u8 {
        let value = value.clamp(0x20, 0xe0);
        let offset = i32::from(value) - 0x80;
        match self {
            Self::Linear => value,
            Self::Progressive => {
                // Same quadratic law/nearest rounding as the reference, with
                // both native sides measuring 96 rather than 128/127.
                let curved = (offset.abs() * offset.abs() + 48) / 96;
                (0x80 + offset.signum() * curved) as u8
            }
            Self::Fbneo => {
                // Normalize each side to the reference table, then restore the
                // native side. Preserve center and full lock exactly.
                let side = if offset < 0 { 128 } else { 127 };
                let index = 128 + offset.signum() * ((offset.abs() * side + 48) / 96);
                let curved = i32::from(FBNEO[index as usize]) - 128;
                let side = if curved < 0 { 128 } else { 127 };
                (128 + curved.signum() * ((curved.abs() * 96 + side / 2) / side)) as u8
            }
        }
    }
}
