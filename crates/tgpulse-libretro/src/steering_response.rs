#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn curves_preserve_native_span_center_and_monotonicity() {
        for response in [Response::Linear, Response::Progressive, Response::Fbneo] {
            assert_eq!(response.apply(0x20), 0x20);
            assert_eq!(response.apply(0x80), 0x80);
            assert_eq!(response.apply(0xe0), 0xe0);
            let mut previous = 0x20;
            for value in 0x20..=0xe0 {
                let out = response.apply(value);
                assert!(out >= previous && (0x20..=0xe0).contains(&out));
                if value.abs_diff(0x80) <= 48 {
                    assert!(out.abs_diff(0x80) <= value.abs_diff(0x80));
                }
                if response == Response::Linear {
                    assert_eq!(out, value);
                }
                previous = out;
            }
        }
        assert_eq!(Response::Progressive.apply(0xb0), 0x98);
        assert_eq!(Response::Progressive.apply(0x50), 0x68);
        assert_eq!(Response::Fbneo.apply(0xb0), 0x8e);
        assert_eq!(Response::Fbneo.apply(0x50), 0x72);
        assert_eq!(Response::parse(Some("bogus")), Response::Linear);
        assert_eq!(Response::parse(None), Response::Linear);
    }
}
